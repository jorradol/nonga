/** Analyze audience and suggest response depth/style before answering. */
export function buildNongAeAudienceGuidance(
  userRole?: SalesBrainUserRole,
  userMessage?: string
): string {
  const t = (userMessage ?? "").trim();
  const isDealerSide =
    userRole === "dealer" ||
    userRole === "seller" ||
    /โชว์รูม|ดีลเลอร์|ลงประกาศ|เขียนโพสต์|ปิด(?:การ)?ขาย|margin|กำไร|stock|สต็อก|นำเข้า/i.test(
      t
    );
  const isBuyerQuick =
    userRole === "buyer" ||
    /^(?:มี|หา|แนะนำ|อยากได้).{0,50}(?:ไหม|มั้ย|หน่อย)?$/i.test(t) ||
    /งบ\s*\d|ไม่เกิน\s*\d/i.test(t);

  if (isDealerSide) {
    return `[แบบการตอบ — วิเคราะห์จากบริบท]
ผู้ใช้เป็นฝั่งขาย/ดีลเลอร์ → ตอบละเอียดขึ้น ใส่ checklist เชิงเทคนิค มุมต้นทุน-กำไร หรือจุดที่ต้องตรวจสภาพ ใช้ภาษามืออาชีพแต่ยังเป็นกันเ�`;
  }
  if (isBuyerQuick) {
    return `[แบบการตอบ — วิเคราะห์จากบริบท]
ผู้ใช้เป็นฝั่งซื้อ / ถามสั้น → ตอบกระชับ สรุปตรงคำถามก่อน 1-2 ประโยค แล้วค่อยเหตุผลสั้นๆ เหมือนเซลล์ที่ฟังความต้องการแล้วช่วยคัดให้ ไม่ยัดสเป็คยาว`;
  }
  return `[แบบการตอบ — วิเคราะห์จากบริบท]
อ่านข้อความก่อนเลือกรูปแบบ: ถามสั้น/ตัดสินใจเร็ว → กระชับ | ถามลึก/เทียบ/เทคนิค → ละเอียดขึ้น อย่าฝืน template เดียวทุกคำถาม`;
}
