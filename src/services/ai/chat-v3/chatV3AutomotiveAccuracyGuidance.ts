/**
 * Detect accuracy topics present in the latest user message.
 */
export function detectChatV3AccuracyTopics(message: string): ChatV3AccuracyTopic[] {
  const text = String(message ?? "").trim();
  if (!text) return [];
  const found: ChatV3AccuracyTopic[] = [];
  const seen = new Set<ChatV3AccuracyTopic>();
  for (const entry of TOPIC_PATTERNS) {
    if (seen.has(entry.topic)) continue;
    if (entry.re.test(text)) {
      seen.add(entry.topic);
      found.push(entry.topic);
    }
  }
  return found;
}

/**
 * Build instruction block for detected accuracy topics.
 */
export function buildChatV3AutomotiveAccuracyGuidanceBlock(
  topics: ChatV3AccuracyTopic[]
): string {
  if (topics.length === 0) return "";
  const lines: string[] = [
    "[ความถูกต้องและความปลอดภัยเชิงเทคนิค — WP-V3-14]",
    "ใช้เป็นกรอบบังคับสำหรับคำถามรอบนี้ — ห้ามอ่านเป็นบทพูดยาวทุกข้อ และยังคงน้ำเสียงเป็นมิตรตามบุคลิก",
  ];
  for (const topic of topics) {
    lines.push(`หัวข้อ ${topic}:`);
    for (const bullet of TOPIC_GUIDANCE[topic]) {
      lines.push(`- ${bullet}`);
    }
  }
  return lines.join("\n");
}
